import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

const copies = [
  ['assets/images/Logo/Full.png', 'public/brand/logo.png'],
  ['assets/images/Logo/Full reverse.png', 'public/brand/logo-reverse.png'],
  ['assets/images/Logo/Mark.png', 'public/brand/mark.png'],
  ['assets/images/Logo/Mark.png', 'public/brand/favicon.png'],
  ['assets/images/Hero.jpg', 'public/images/hero.jpg'],
  ['assets/images/Login-desktop.png', 'public/images/login.png'],
]

const iconSource = 'assets/icons/Icon'
const iconTarget = 'src/assets/icons'
const iconNamesFile = 'src/components/ui/iconNames.ts'

for (const [from, to] of copies) {
  mkdirSync(join(to, '..'), { recursive: true })
  copyFileSync(from, to)
}

// Strokes become currentColor so icons take the colour of their text.
function toCurrentColor(svg) {
  return svg
    .replace(/stroke="(?!none)[^"]*"/g, 'stroke="currentColor"')
    .replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"')
}

mkdirSync(iconTarget, { recursive: true })
const iconNames = readdirSync(iconSource)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => {
    writeFileSync(join(iconTarget, file), toCurrentColor(readFileSync(join(iconSource, file), 'utf8')))
    return basename(file, '.svg')
  })
  .sort()

const namesSource = [
  '// Generated by scripts/copy-assets.mjs. Do not edit.',
  'export const iconNames = [',
  ...iconNames.map((name) => `  '${name}',`),
  '] as const',
  '',
  'export type IconName = (typeof iconNames)[number]',
  '',
].join('\n')
writeFileSync(iconNamesFile, namesSource)

console.log(`copy-assets: ${copies.length} files copied, ${iconNames.length} icons converted to currentColor.`)
